import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

/// Represents the health status of a FLRD Doctor environment component.
enum DoctorItemStatus {
  healthy,
  warning,
  missing,
}

/// Represents an individual diagnostic check parsed from `flutter doctor -v`
/// or probed directly on the host PC (Git, JDK, Ninja/NDK, ADB).
class DoctorItem {
  final String id;
  final String title;
  final DoctorItemStatus status;
  final String details;
  final String? solutionGuidance;
  final String? actionCommand;
  final String? actionUrl;

  const DoctorItem({
    required this.id,
    required this.title,
    required this.status,
    required this.details,
    this.solutionGuidance,
    this.actionCommand,
    this.actionUrl,
  });

  bool get isHealthy => status == DoctorItemStatus.healthy;
  bool get isWarning => status == DoctorItemStatus.warning;
  bool get isMissing => status == DoctorItemStatus.missing;

  bool get hasAction =>
      (actionCommand != null && actionCommand!.trim().isNotEmpty) ||
      (actionUrl != null && actionUrl!.trim().isNotEmpty);

  DoctorItem copyWith({
    String? id,
    String? title,
    DoctorItemStatus? status,
    String? details,
    String? solutionGuidance,
    String? actionCommand,
    String? actionUrl,
  }) {
    return DoctorItem(
      id: id ?? this.id,
      title: title ?? this.title,
      status: status ?? this.status,
      details: details ?? this.details,
      solutionGuidance: solutionGuidance ?? this.solutionGuidance,
      actionCommand: actionCommand ?? this.actionCommand,
      actionUrl: actionUrl ?? this.actionUrl,
    );
  }

  @override
  String toString() =>
      'DoctorItem(id: $id, title: $title, status: $status, hasAction: $hasAction)';
}

/// Full diagnostic report generated by FLRD Doctor.
class DoctorReport {
  final bool isScanning;
  final int healthyCount;
  final int totalCount;
  final List<DoctorItem> items;
  final String? rawOutput;
  final String? error;

  const DoctorReport({
    this.isScanning = false,
    this.healthyCount = 0,
    this.totalCount = 0,
    this.items = const [],
    this.rawOutput,
    this.error,
  });

  factory DoctorReport.initial() => const DoctorReport(
        isScanning: false,
        healthyCount: 0,
        totalCount: 0,
        items: [],
      );

  factory DoctorReport.scanning() => const DoctorReport(
        isScanning: true,
        healthyCount: 0,
        totalCount: 0,
        items: [],
      );

  /// Pre-flight report when Flutter SDK is missing from the system PATH.
  factory DoctorReport.missingSdk({String? error}) {
    final isWindows = Platform.isWindows;
    final item = DoctorItem(
      id: 'flutter_sdk',
      title: 'Flutter SDK',
      status: DoctorItemStatus.missing,
      details: 'Flutter executable was not found in your system PATH.\n'
          'The Flutter SDK is required to build, test, and run your desktop and mobile applications.',
      solutionGuidance:
          'Download and extract the Flutter SDK into a directory without spaces '
          '(e.g. C:\\src\\flutter on Windows or ~/flutter on macOS/Linux), '
          'then append its "bin" directory to your system PATH environment variable.',
      actionCommand: isWindows ? 'winget install Google.Flutter' : null,
      actionUrl: 'https://docs.flutter.dev/get-started/install',
    );

    return DoctorReport(
      isScanning: false,
      healthyCount: 0,
      totalCount: 1,
      items: [item],
      rawOutput: 'Flutter executable not found in PATH.',
      error: error ?? 'Flutter SDK is not installed or not available in system PATH.',
    );
  }

  /// Report for Web Sandbox environments where native shell execution is unavailable.
  factory DoctorReport.webSandbox() {
    const items = [
      DoctorItem(
        id: 'flutter_web',
        title: 'Flutter Web Sandbox',
        status: DoctorItemStatus.healthy,
        details: 'Running within web preview sandbox environment.',
        solutionGuidance: 'Full native compilation tools require desktop execution.',
      ),
      DoctorItem(
        id: 'browser_engine',
        title: 'Browser Runtime & CanvasKit',
        status: DoctorItemStatus.healthy,
        details: 'Chromium / CanvasKit rendering engine active.',
      ),
    ];
    return const DoctorReport(
      isScanning: false,
      healthyCount: 2,
      totalCount: 2,
      items: items,
      rawOutput: '[√] Flutter Web Sandbox\n[√] Browser Runtime & CanvasKit',
    );
  }

  /// Items already configured and healthy on this PC.
  List<DoctorItem> get healthyItems =>
      items.where((item) => item.status == DoctorItemStatus.healthy).toList();

  /// Pending items (warnings and missing) in report order needing setup or action.
  List<DoctorItem> get pendingItems => items
      .where((item) => item.status != DoctorItemStatus.healthy)
      .toList();

  /// Percentage score (0-100) of healthy components.
  int get scorePercentage =>
      totalCount > 0 ? ((healthyCount / totalCount) * 100).round() : 0;

  /// Fractional health score (0.0 - 1.0).
  double get healthScore =>
      totalCount > 0 ? (healthyCount / totalCount) : 0.0;

  /// True if any component is missing or has a warning.
  bool get hasIssues =>
      items.any((item) => item.status != DoctorItemStatus.healthy);

  /// True if all parsed items are completely healthy.
  bool get isAllHealthy => totalCount > 0 && healthyCount == totalCount;

  /// Number of items with warning status.
  int get warningCount =>
      items.where((item) => item.status == DoctorItemStatus.warning).length;

  /// Number of items with missing/error status.
  int get missingCount =>
      items.where((item) => item.status == DoctorItemStatus.missing).length;

  /// Formats a human-readable Markdown checklist separating ready vs pending items.
  String toChecklistMarkdown({bool pt = true}) {
    final ready = healthyItems;
    final pending = pendingItems;
    final buf = StringBuffer()
      ..writeln(
        pt
            ? '# FLRD Doctor — Diagnóstico do PC ($healthyCount/$totalCount prontos • $scorePercentage%)'
            : '# FLRD Doctor — PC Environment Checklist ($healthyCount/$totalCount ready • $scorePercentage%)',
      )
      ..writeln()
      ..writeln(pt ? '## ✅ Já Prontos no PC (${ready.length})' : '## ✅ Ready on This PC (${ready.length})');

    if (ready.isEmpty) {
      buf.writeln(pt ? '- Nenhum componente pronto ainda.' : '- No healthy components yet.');
    } else {
      for (final item in ready) {
        final firstLine = item.details
            .split('\n')
            .map((l) => l.trim())
            .firstWhere((l) => l.isNotEmpty, orElse: () => '');
        buf.writeln(firstLine.isNotEmpty ? '- [x] **${item.title}** — $firstLine' : '- [x] **${item.title}**');
      }
    }

    buf
      ..writeln()
      ..writeln(pt ? '## ⚠️ Pendentes (${pending.length})' : '## ⚠️ Pending Setup (${pending.length})');

    if (pending.isEmpty) {
      buf.writeln(pt ? '- Nenhuma pendência encontrada neste PC.' : '- No pending items.');
    } else {
      for (final item in pending) {
        final tag = item.isMissing
            ? (pt ? 'Faltando' : 'Missing')
            : (pt ? 'Aviso' : 'Warning');
        buf.writeln('- [ ] **[$tag] ${item.title}**');
        if (item.solutionGuidance != null && item.solutionGuidance!.trim().isNotEmpty) {
          buf.writeln('  - Solução: ${item.solutionGuidance!.trim()}');
        }
        if (item.actionCommand != null && item.actionCommand!.trim().isNotEmpty) {
          buf.writeln('  - Comando: `${item.actionCommand!.trim()}`');
        }
      }
    }

    return buf.toString().trimRight();
  }

  DoctorReport copyWith({
    bool? isScanning,
    int? healthyCount,
    int? totalCount,
    List<DoctorItem>? items,
    String? rawOutput,
    String? error,
  }) {
    return DoctorReport(
      isScanning: isScanning ?? this.isScanning,
      healthyCount: healthyCount ?? this.healthyCount,
      totalCount: totalCount ?? this.totalCount,
      items: items ?? this.items,
      rawOutput: rawOutput ?? this.rawOutput,
      error: error ?? this.error,
    );
  }
}

/// Runner function signature allowing dependency injection and mocking in tests.
typedef DoctorProcessRunner = Future<ProcessResult> Function(
  String executable,
  List<String> arguments, {
  bool runInShell,
});

/// Environment map provider for testability.
typedef DoctorEnvironmentProvider = Map<String, String> Function();

/// Pure Dart diagnostic engine shared by the UI (`FlutterDoctorService`)
/// and the CLI (`bin/flrd.dart doctor`).
class DoctorAnalyzer {
  DoctorAnalyzer._();

  static Future<ProcessResult> defaultProcessRunner(
    String executable,
    List<String> arguments, {
    bool runInShell = true,
  }) {
    return Process.run(
      executable,
      arguments,
      runInShell: runInShell,
      stdoutEncoding: const Utf8Codec(allowMalformed: true),
      stderrEncoding: const Utf8Codec(allowMalformed: true),
    );
  }

  /// Executes `flutter doctor -v`, optionally runs host PC toolchain probes
  /// (Git, JDK 17/21 compatibility, Ninja/Android NDK, ADB), and builds a [DoctorReport].
  static Future<DoctorReport> runDiagnostics({
    DoctorProcessRunner? processRunner,
    DoctorEnvironmentProvider? environmentProvider,
    bool includeExtendedPcChecks = true,
  }) async {
    final runner = processRunner ?? defaultProcessRunner;
    final env = (environmentProvider ?? () => Platform.environment)();

    try {
      final isWindows = Platform.isWindows;
      final locatorCmd = isWindows ? 'where.exe' : 'which';

      var flutterFoundInPath = true;
      try {
        final locatorRes = await runner(
          locatorCmd,
          ['flutter'],
          runInShell: isWindows,
        );
        if (locatorRes.exitCode != 0) {
          flutterFoundInPath = false;
        }
      } catch (_) {
        // Proceed directly if locator binary is absent.
      }

      if (!flutterFoundInPath) {
        final missingReport = DoctorReport.missingSdk(
          error: 'Flutter executable not found in system PATH.',
        );
        if (!includeExtendedPcChecks) {
          return missingReport;
        }
        final extraItems = await runExtendedPcProbes(
          runner: runner,
          env: env,
        );
        return _mergeReportWithExtras(missingReport, extraItems);
      }

      final doctorRes = await runner(
        'flutter',
        ['doctor', '-v'],
        runInShell: true,
      );

      final stdoutText = doctorRes.stdout?.toString() ?? '';
      final stderrText = doctorRes.stderr?.toString() ?? '';
      final combinedOutput = '$stdoutText\n$stderrText'.trim();

      if (combinedOutput.isEmpty && doctorRes.exitCode != 0) {
        final missingReport = DoctorReport.missingSdk(
          error: 'Flutter doctor exited with code ${doctorRes.exitCode}.',
        );
        if (!includeExtendedPcChecks) {
          return missingReport;
        }
        final extraItems = await runExtendedPcProbes(
          runner: runner,
          env: env,
        );
        return _mergeReportWithExtras(missingReport, extraItems);
      }

      final parsedReport = parseDoctorOutput(combinedOutput);
      if (parsedReport.items.isEmpty) {
        return DoctorReport(
          isScanning: false,
          healthyCount: 0,
          totalCount: 0,
          items: const [],
          rawOutput: combinedOutput,
          error: combinedOutput.isNotEmpty
              ? 'Could not parse flutter doctor output.'
              : 'Doctor output was empty.',
        );
      }

      if (!includeExtendedPcChecks) {
        return parsedReport;
      }

      final extraItems = await runExtendedPcProbes(
        runner: runner,
        env: env,
        existingRawOutput: combinedOutput,
      );
      return _mergeReportWithExtras(parsedReport, extraItems);
    } catch (e) {
      return DoctorReport.missingSdk(error: e.toString());
    }
  }

  static DoctorReport _mergeReportWithExtras(
    DoctorReport base,
    List<DoctorItem> extras,
  ) {
    if (extras.isEmpty) return base;
    final merged = <DoctorItem>[...base.items];
    final existingIds = merged.map((i) => i.id).toSet();
    for (final extra in extras) {
      if (existingIds.add(extra.id)) {
        merged.add(extra);
      }
    }
    final healthyCount =
        merged.where((i) => i.status == DoctorItemStatus.healthy).length;
    return base.copyWith(
      healthyCount: healthyCount,
      totalCount: merged.length,
      items: merged,
    );
  }

  /// Runs real host PC checks beyond `flutter doctor -v` (Git, Java/JDK Gradle
  /// compatibility, Ninja/NDK C++ native build tools, and ADB USB readiness).
  static Future<List<DoctorItem>> runExtendedPcProbes({
    required DoctorProcessRunner runner,
    required Map<String, String> env,
    String existingRawOutput = '',
  }) async {
    final checks = await Future.wait<DoctorItem?>([
      _probeGit(runner),
      _probeCompatibleJavaJdk(runner, env, existingRawOutput),
      _probeNativeBuildToolchain(runner, env, existingRawOutput),
      _probeAdbUsbReadiness(runner, env, existingRawOutput),
    ]);
    return checks.whereType<DoctorItem>().toList(growable: false);
  }

  static Future<DoctorItem> _probeGit(DoctorProcessRunner runner) async {
    try {
      final res = await runner('git', ['--version'], runInShell: true);
      final out = '${res.stdout ?? ''} ${res.stderr ?? ''}'.trim();
      if (res.exitCode == 0 && out.isNotEmpty) {
        return DoctorItem(
          id: 'git_cli',
          title: 'Git CLI (Controle de Versão & Pacotes)',
          status: DoctorItemStatus.healthy,
          details: '• $out\n• Necessário para pub get de repositórios Git e submódulos nativos.',
        );
      }
    } catch (_) {}

    return DoctorItem(
      id: 'git_cli',
      title: 'Git CLI (Controle de Versão & Pacotes)',
      status: DoctorItemStatus.missing,
      details: '✗ Git não encontrado no PATH do sistema.',
      solutionGuidance:
          'Instale o Git para clonar dependências pub/git e submódulos C/C++ (ex.: ggml / stable-diffusion).',
      actionCommand: Platform.isWindows ? 'winget install Git.Git' : null,
      actionUrl: 'https://git-scm.com/downloads',
    );
  }

  static Future<DoctorItem> _probeCompatibleJavaJdk(
    DoctorProcessRunner runner,
    Map<String, String> env,
    String existingRawOutput,
  ) async {
    String? configuredJdkDir;
    try {
      final cfgRes = await runner('flutter', ['config', '--list'], runInShell: true);
      final cfgOut = '${cfgRes.stdout ?? ''}\n${cfgRes.stderr ?? ''}';
      final match = RegExp(r'jdk-dir:\s*(.+)').firstMatch(cfgOut);
      if (match != null) {
        final raw = match.group(1)?.trim() ?? '';
        if (raw.isNotEmpty && raw != '(Not set)') {
          configuredJdkDir = raw;
        }
      }
    } catch (_) {}

    final activeJavaBinary = configuredJdkDir != null
        ? p.join(
            configuredJdkDir,
            'bin',
            Platform.isWindows ? 'java.exe' : 'java',
          )
        : 'java';

    String javaVersionOutput = '';
    int? activeMajor;
    try {
      final res = await runner(activeJavaBinary, ['-version'], runInShell: true);
      javaVersionOutput = '${res.stdout ?? ''}\n${res.stderr ?? ''}'.trim();
      final match = RegExp(r'version\s+"(\d+)(?:\.(\d+))?').firstMatch(javaVersionOutput);
      if (match != null) {
        final first = int.tryParse(match.group(1) ?? '');
        activeMajor = first == 1 ? int.tryParse(match.group(2) ?? '') : first;
      }
    } catch (_) {}

    if (activeMajor == null) {
      final doctorJavaMatch =
          RegExp(r'Java version .*?\(build (\d+)').firstMatch(existingRawOutput);
      if (doctorJavaMatch != null) {
        activeMajor = int.tryParse(doctorJavaMatch.group(1) ?? '');
      }
    }

    final compatibleJdk = _findFirstCompatibleLtsJdk(env);

    if (activeMajor != null && activeMajor >= 17 && activeMajor <= 21) {
      final sourceLabel = configuredJdkDir != null
          ? '• Configurado no Flutter (--jdk-dir): $configuredJdkDir'
          : '• Detectado no PATH / Android Studio JBR';
      return DoctorItem(
        id: 'java_jdk_lts',
        title: 'Java / JDK Compatível (Gradle Android)',
        status: DoctorItemStatus.healthy,
        details: '• Java LTS $activeMajor ativo e compatível com Gradle 8.x/9.x\n$sourceLabel',
      );
    }

    if (activeMajor != null && activeMajor > 21) {
      final fixCmd = compatibleJdk != null
          ? 'flutter config --jdk-dir="${compatibleJdk.path}"'
          : null;
      return DoctorItem(
        id: 'java_jdk_lts',
        title: 'Java / JDK Compatível (Gradle Android)',
        status: DoctorItemStatus.warning,
        details: '• Java ativo no momento: $activeMajor (incompatível com Gradle 8.x padrão).\n'
            '${compatibleJdk != null ? "• JDK compatível já encontrado no PC: Java ${compatibleJdk.major} em ${compatibleJdk.path}" : "• Nenhum JDK 17/21 LTS encontrado automaticamente."}',
        solutionGuidance: compatibleJdk != null
            ? 'Você já tem o JDK ${compatibleJdk.major} instalado neste PC! Aponte o Flutter para ele usando o comando abaixo para evitar erro do Gradle.'
            : 'Instale o Eclipse Temurin JDK 17 ou 21 (LTS) e aponte com `flutter config --jdk-dir=...`.',
        actionCommand: fixCmd ??
            (Platform.isWindows
                ? 'winget install EclipseAdoptium.Temurin.17.JDK'
                : null),
        actionUrl: 'https://adoptium.net/',
      );
    }

    if (compatibleJdk != null) {
      return DoctorItem(
        id: 'java_jdk_lts',
        title: 'Java / JDK Compatível (Gradle Android)',
        status: DoctorItemStatus.warning,
        details: '• Java padrão não detectado no PATH.\n'
            '• JDK ${compatibleJdk.major} encontrado no PC: ${compatibleJdk.path}',
        solutionGuidance:
            'Vincule o JDK já instalado ao Flutter para compilar APKs sem depender do PATH global.',
        actionCommand: 'flutter config --jdk-dir="${compatibleJdk.path}"',
        actionUrl: 'https://adoptium.net/',
      );
    }

    return DoctorItem(
      id: 'java_jdk_lts',
      title: 'Java / JDK Compatível (Gradle Android)',
      status: DoctorItemStatus.missing,
      details: '✗ Nenhum Java JDK 17/21 (LTS) detectado para builds Gradle/Android.',
      solutionGuidance:
          'Instale o OpenJDK 17 LTS (Temurin) ou Android Studio JBR para compilar apps Android.',
      actionCommand: Platform.isWindows
          ? 'winget install EclipseAdoptium.Temurin.17.JDK'
          : null,
      actionUrl: 'https://adoptium.net/',
    );
  }

  static Future<DoctorItem> _probeNativeBuildToolchain(
    DoctorProcessRunner runner,
    Map<String, String> env,
    String existingRawOutput,
  ) async {
    String? ninjaVersion;
    try {
      final res = await runner('ninja', ['--version'], runInShell: true);
      if (res.exitCode == 0) {
        final v = (res.stdout?.toString() ?? '').trim();
        if (v.isNotEmpty) ninjaVersion = v;
      }
    } catch (_) {}

    if (ninjaVersion == null && Platform.isWindows) {
      ninjaVersion = _findWinGetNinjaPath(env) != null ? 'WinGet Ninja' : null;
    }

    final sdkPath = _resolveAndroidSdkPath(env, existingRawOutput);
    final ndkVersions = _listInstalledNdkVersions(sdkPath);

    if (ninjaVersion != null && ndkVersions.isNotEmpty) {
      return DoctorItem(
        id: 'native_cpp_toolchain',
        title: 'Toolchain Nativa C++ / NDK (Ninja & glslc)',
        status: DoctorItemStatus.healthy,
        details: '• Ninja: $ninjaVersion\n'
            '• Android NDK instalado: ${ndkVersions.join(", ")}\n'
            '• Pronto para compilar bibliotecas nativas C++/CMake/Vulkan.',
      );
    }

    final missingParts = <String>[
      if (ninjaVersion == null) 'Ninja build tool',
      if (ndkVersions.isEmpty) 'Android NDK (Side by side)',
    ];

    return DoctorItem(
      id: 'native_cpp_toolchain',
      title: 'Toolchain Nativa C++ / NDK (Ninja & glslc)',
      status: DoctorItemStatus.warning,
      details: '• Ninja: ${ninjaVersion ?? "não encontrado no PATH"}\n'
          '• Android NDK: ${ndkVersions.isEmpty ? "nenhuma versão instalada em $sdkPath" : ndkVersions.join(", ")}\n'
          '! Pendente para apps com C++/JNI/Vulkan: ${missingParts.join(" + ")}.',
      solutionGuidance: ninjaVersion == null
          ? 'Instale o Ninja (`winget install Ninja-build.Ninja`) e o Android NDK via SDK Manager caso o projeto utilize código nativo C++.'
          : 'No Android Studio > SDK Manager > SDK Tools, marque "NDK (Side by side)" e "CMake" para habilitar builds C++/JNI.',
      actionCommand: ninjaVersion == null && Platform.isWindows
          ? 'winget install Ninja-build.Ninja'
          : null,
      actionUrl: 'https://developer.android.com/ndk/downloads',
    );
  }

  static Future<DoctorItem> _probeAdbUsbReadiness(
    DoctorProcessRunner runner,
    Map<String, String> env,
    String existingRawOutput,
  ) async {
    final adbExe = _resolveAdbExecutable(env, existingRawOutput);
    try {
      final res = await runner(adbExe, ['devices', '-l'], runInShell: true);
      if (res.exitCode == 0) {
        final lines = (res.stdout?.toString() ?? '')
            .split(RegExp(r'\r?\n'))
            .map((l) => l.trim())
            .where((l) => l.isNotEmpty && !l.startsWith('List of devices'))
            .toList();

        final authorized = lines.where((l) => RegExp(r'\sdevice\b').hasMatch(l)).toList();
        final unauthorized = lines.where((l) => l.contains('unauthorized')).toList();

        if (authorized.isNotEmpty) {
          return DoctorItem(
            id: 'adb_usb',
            title: 'ADB & Celular USB (Deploy Android)',
            status: DoctorItemStatus.healthy,
            details: '• ADB pronto: $adbExe\n'
                '• ${authorized.length} dispositivo(s) autorizado(s): ${authorized.join(" | ")}',
          );
        }

        if (unauthorized.isNotEmpty) {
          return DoctorItem(
            id: 'adb_usb',
            title: 'ADB & Celular USB (Deploy Android)',
            status: DoctorItemStatus.warning,
            details: '• ADB pronto em: $adbExe\n'
                '! Dispositivo aguardando autorização na tela do celular: ${unauthorized.first}',
            solutionGuidance:
                'Desbloqueie o celular e toque em "Permitir depuração USB sempre neste computador".',
            actionCommand: 'adb devices',
          );
        }

        return DoctorItem(
          id: 'adb_usb',
          title: 'ADB & Celular USB (Deploy Android)',
          status: DoctorItemStatus.healthy,
          details: '• ADB pronto neste PC: $adbExe\n'
              '• Nenhum celular conectado no momento (conecte via cabo USB com Depuração USB ativa quando quiser rodar no aparelho).',
        );
      }
    } catch (_) {}

    return DoctorItem(
      id: 'adb_usb',
      title: 'ADB & Celular USB (Deploy Android)',
      status: DoctorItemStatus.warning,
      details: '! Executável adb não encontrado no PATH nem no platform-tools.',
      solutionGuidance:
          'Instale Android SDK Platform-Tools no Android Studio ou via WinGet para instalar e depurar apps direto no celular.',
      actionCommand: Platform.isWindows
          ? 'winget install Google.PlatformTools'
          : null,
      actionUrl: 'https://developer.android.com/tools/releases/platform-tools',
    );
  }

  static ({String path, int major})? _findFirstCompatibleLtsJdk(
    Map<String, String> env,
  ) {
    final searchRoots = <String>[
      if (env['JAVA_HOME'] != null && env['JAVA_HOME']!.trim().isNotEmpty)
        env['JAVA_HOME']!.trim(),
      if (Platform.isWindows) ...[
        r'C:\Program Files\Eclipse Adoptium',
        r'C:\Program Files\Java',
        r'C:\Program Files\Microsoft',
        r'C:\Program Files\Zulu',
        r'C:\Program Files\Android\Android Studio\jbr',
      ] else if (Platform.isMacOS) ...[
        '/Library/Java/JavaVirtualMachines',
        '/Applications/Android Studio.app/Contents/jbr/Contents/Home',
      ] else ...[
        '/usr/lib/jvm',
      ],
    ];

    for (final root in searchRoots) {
      final rootDir = Directory(root);
      if (!rootDir.existsSync()) continue;

      final candidateDirs = <Directory>[
        rootDir,
        ...rootDir.listSync(followLinks: false).whereType<Directory>(),
      ];

      for (final dir in candidateDirs) {
        final releaseFile = File(p.join(dir.path, 'release'));
        final javaBin = File(
          p.join(dir.path, 'bin', Platform.isWindows ? 'java.exe' : 'java'),
        );
        if (!javaBin.existsSync()) continue;

        int? major;
        if (releaseFile.existsSync()) {
          try {
            final content = releaseFile.readAsStringSync();
            final m = RegExp(r'JAVA_VERSION="(\d+)(?:\.(\d+))?').firstMatch(content);
            if (m != null) {
              final first = int.tryParse(m.group(1) ?? '');
              major = first == 1 ? int.tryParse(m.group(2) ?? '') : first;
            }
          } catch (_) {}
        }
        if (major != null && major >= 17 && major <= 21) {
          return (path: dir.path, major: major);
        }
      }
    }
    return null;
  }

  static String? _findWinGetNinjaPath(Map<String, String> env) {
    final localAppData = env['LOCALAPPDATA'] ?? '';
    if (localAppData.isEmpty) return null;
    final wingetPkg = Directory(p.join(localAppData, 'Microsoft', 'WinGet', 'Packages'));
    if (!wingetPkg.existsSync()) return null;
    try {
      for (final pkg in wingetPkg.listSync(followLinks: false).whereType<Directory>()) {
        if (!p.basename(pkg.path).toLowerCase().contains('ninja')) continue;
        final exe = File(p.join(pkg.path, 'ninja.exe'));
        if (exe.existsSync()) return exe.path;
      }
    } catch (_) {}
    return null;
  }

  static String? _resolveAndroidSdkPath(
    Map<String, String> env,
    String existingRawOutput,
  ) {
    final sdkMatch = RegExp(r'Android SDK at\s+(.+)').firstMatch(existingRawOutput);
    if (sdkMatch != null) {
      final p1 = sdkMatch.group(1)?.trim() ?? '';
      if (p1.isNotEmpty) return p1;
    }
    final fromEnv = env['ANDROID_SDK_ROOT'] ?? env['ANDROID_HOME'];
    if (fromEnv != null && fromEnv.trim().isNotEmpty) {
      return fromEnv.trim();
    }
    if (Platform.isWindows && env['LOCALAPPDATA'] != null) {
      final candidate = p.join(env['LOCALAPPDATA']!, 'Android', 'Sdk');
      if (Directory(candidate).existsSync()) return candidate;
    }
    return null;
  }

  static List<String> _listInstalledNdkVersions(String? sdkPath) {
    if (sdkPath == null || sdkPath.isEmpty) return const [];
    final ndkDir = Directory(p.join(sdkPath, 'ndk'));
    if (!ndkDir.existsSync()) return const [];
    try {
      return ndkDir
          .listSync(followLinks: false)
          .whereType<Directory>()
          .map((d) => p.basename(d.path))
          .where((v) => v.isNotEmpty && !v.startsWith('.'))
          .toList()
        ..sort();
    } catch (_) {
      return const [];
    }
  }

  static String _resolveAdbExecutable(
    Map<String, String> env,
    String existingRawOutput,
  ) {
    final sdkPath = _resolveAndroidSdkPath(env, existingRawOutput);
    if (sdkPath != null) {
      final candidate = File(
        p.join(
          sdkPath,
          'platform-tools',
          Platform.isWindows ? 'adb.exe' : 'adb',
        ),
      );
      if (candidate.existsSync()) return candidate.path;
    }
    return 'adb';
  }

  /// Normalizes common Windows UTF-8 decoded-as-Latin1 doctor symbols (e.g. `[âˆš]`).
  static String _normalizeMojibakeSymbols(String text) {
    return text
        .replaceAll('[âˆš]', '[√]')
        .replaceAll('[âœ“]', '[✓]')
        .replaceAll('[âœ—]', '[✗]')
        .replaceAll('[û]', '[√]')
        .replaceAll('â€¢', '•');
  }

  /// Parses raw `flutter doctor -v` string output into a structured [DoctorReport].
  static DoctorReport parseDoctorOutput(String rawOutput) {
    if (rawOutput.trim().isEmpty) {
      return DoctorReport.initial();
    }

    final normalizedOutput = _normalizeMojibakeSymbols(rawOutput);
    final lines = normalizedOutput.split(RegExp(r'\r?\n'));
    final List<DoctorItem> items = [];

    // Header regex: [√], [✓], [!], [X], [x], [✗], [+], [-]
    final headerRegex = RegExp(r'^[ \t]*\[([√✓xX✗!+?•\-])\]\s*(.+)$');

    String? currentSymbol;
    String? currentTitle;
    final List<String> currentDetails = [];

    void finalizeCurrentItem() {
      if (currentSymbol == null || currentTitle == null) return;

      final status = _mapSymbolToStatus(currentSymbol!);
      final rawTitle = currentTitle!.trim();
      final cleanedTitle = rawTitle
          .replaceAll(RegExp(r'\s*\[\d+(?:\.\d+)?m?s\]\s*$'), '')
          .trim();

      final details = currentDetails.join('\n').trim();
      final id = _generateId(cleanedTitle, items.length);

      final rawItem = DoctorItem(
        id: id,
        title: cleanedTitle,
        status: status,
        details: details,
      );

      final enrichedItem = enrichDoctorItem(rawItem);
      items.add(enrichedItem);

      currentSymbol = null;
      currentTitle = null;
      currentDetails.clear();
    }

    for (final line in lines) {
      final match = headerRegex.firstMatch(line);
      if (match != null) {
        finalizeCurrentItem();
        currentSymbol = match.group(1);
        currentTitle = match.group(2);
      } else {
        final trimmed = line.trim();
        final isFooter = trimmed.startsWith('! Doctor found issues') ||
            trimmed.startsWith('• No issues found!') ||
            trimmed.startsWith('! No issues found') ||
            trimmed.startsWith('• Doctor found');

        if (isFooter) {
          finalizeCurrentItem();
        } else if (currentSymbol != null) {
          currentDetails.add(line);
        }
      }
    }

    finalizeCurrentItem();

    final healthyCount =
        items.where((i) => i.status == DoctorItemStatus.healthy).length;

    return DoctorReport(
      isScanning: false,
      healthyCount: healthyCount,
      totalCount: items.length,
      items: items,
      rawOutput: normalizedOutput,
    );
  }

  static DoctorItemStatus _mapSymbolToStatus(String symbol) {
    switch (symbol) {
      case '√':
      case '✓':
      case '+':
        return DoctorItemStatus.healthy;
      case '!':
        return DoctorItemStatus.warning;
      case 'X':
      case 'x':
      case '✗':
        return DoctorItemStatus.missing;
      default:
        return DoctorItemStatus.warning;
    }
  }

  static String _generateId(String title, int index) {
    final lower = title.toLowerCase();
    if (lower.startsWith('flutter')) return 'flutter';
    if (lower.contains('android studio')) return 'android_studio';
    if (lower.contains('android toolchain') ||
        (lower.contains('android') && !lower.contains('studio'))) {
      return 'android_toolchain';
    }
    if (lower.contains('windows version')) return 'windows_version';
    if (lower.contains('visual studio')) return 'visual_studio';
    if (lower.contains('xcode')) return 'xcode';
    if (lower.contains('chrome')) return 'chrome';
    if (lower.contains('linux toolchain') || lower.contains('linux')) {
      return 'linux_toolchain';
    }
    if (lower.contains('connected device')) return 'connected_device';
    if (lower.contains('network resources') || lower.contains('network')) {
      return 'network_resources';
    }
    if (lower.contains('cocoapods')) return 'cocoapods';

    final slug = lower
        .split(RegExp(r'[^a-z0-9]+'))
        .where((s) => s.isNotEmpty)
        .take(3)
        .join('_');

    return slug.isNotEmpty ? slug : 'doctor_item_$index';
  }

  /// Enriches a [DoctorItem] with actionable quick-fix URLs, terminal commands,
  /// and human-friendly step-by-step guidance.
  static DoctorItem enrichDoctorItem(DoctorItem item) {
    if (item.status == DoctorItemStatus.healthy) {
      return item;
    }

    String? solutionGuidance = item.solutionGuidance;
    String? actionCommand = item.actionCommand;
    String? actionUrl = item.actionUrl;

    final titleLower = item.title.toLowerCase();
    final detailsLower = item.details.toLowerCase();

    if (detailsLower.contains('android-licenses') ||
        detailsLower.contains('licenses not accepted') ||
        detailsLower.contains('licenses of some android sdk') ||
        detailsLower.contains('license status')) {
      final missingCmdlineTools =
          detailsLower.contains('cmdline-tools component is missing') ||
          detailsLower.contains('cmdline-tools');
      solutionGuidance = missingCmdlineTools
          ? '1) Instale "Android SDK Command-line Tools (latest)" em Android Studio > SDK Manager > SDK Tools.\n'
              '2) Depois execute `flutter doctor --android-licenses` no terminal e aceite todos os termos.'
          : 'Accept the Android SDK platform licenses by executing the license command in your terminal and accepting all terms.';
      actionCommand = 'flutter doctor --android-licenses';
      actionUrl ??= missingCmdlineTools
          ? 'https://developer.android.com/studio#command-line-tools-only'
          : 'https://flutter.dev/to/windows-android-setup';
    } else if (item.id == 'android_toolchain' ||
        item.id == 'android_studio' ||
        titleLower.contains('android')) {
      if (detailsLower.contains('unable to locate android sdk') ||
          detailsLower.contains('android studio not installed') ||
          detailsLower.contains('android sdk not found') ||
          detailsLower.contains('install android studio')) {
        solutionGuidance =
            'Install Android Studio to configure the official Android SDK, Platform-Tools, and Virtual Device Emulators.';
        actionUrl ??= 'https://developer.android.com/studio';
        if (detailsLower.contains('flutter config --android-sdk')) {
          actionCommand = 'flutter config --android-sdk';
        }
      } else if (detailsLower.contains('cmdline-tools component is missing') ||
          detailsLower.contains('cmdline-tools')) {
        solutionGuidance =
            'Open Android Studio > SDK Manager > SDK Tools tab, check "Android SDK Command-line Tools (latest)", and click Apply.';
        actionUrl ??= 'https://developer.android.com/studio';
      }
    } else if (item.id == 'visual_studio' || titleLower.contains('visual studio')) {
      solutionGuidance =
          'Install Visual Studio 2022 with the "Desktop development with C++" workload '
          '(including MSVC v143 and Windows 10/11 SDK) to build native Windows desktop applications.';
      actionUrl ??= 'https://visualstudio.microsoft.com/downloads/';
      if (Platform.isWindows) {
        actionCommand ??= 'winget install Microsoft.VisualStudio.2022.BuildTools';
      }
    } else if (item.id == 'chrome' || titleLower.contains('chrome')) {
      solutionGuidance =
          'Install Google Chrome to develop, debug, and preview Flutter Web applications.';
      actionUrl ??= 'https://www.google.com/chrome/';
    } else if (item.id == 'cocoapods' ||
        titleLower.contains('cocoapods') ||
        detailsLower.contains('cocoapods not installed') ||
        detailsLower.contains('cocoapods')) {
      solutionGuidance =
          'Install CocoaPods to resolve iOS and macOS native pod dependencies.';
      actionCommand = 'sudo gem install cocoapods';
      actionUrl = 'https://guides.cocoapods.org/using/getting-started.html';
    } else if (item.id == 'xcode' || titleLower.contains('xcode')) {
      solutionGuidance =
          'Install Xcode from the Mac App Store and run initial command-line setup to support iOS and macOS development.';
      actionUrl ??= 'https://developer.apple.com/xcode/';
      actionCommand ??=
          'sudo xcode-select --switch /Applications/Xcode.app/Contents/Developer && sudo xcodebuild -runFirstLaunch';
    } else if (item.id == 'linux_toolchain' || titleLower.contains('linux')) {
      solutionGuidance =
          'Install required Linux build packages (clang, cmake, ninja-build, pkg-config, libgtk-3-dev).';
      actionCommand ??=
          'sudo apt-get install clang cmake ninja-build pkg-config libgtk-3-dev';
      actionUrl ??= 'https://docs.flutter.dev/get-started/install/linux/desktop';
    } else if (item.id == 'connected_device' ||
        titleLower.contains('connected device')) {
      solutionGuidance =
          'Connect a physical device via USB with USB debugging enabled, or launch an emulator / desktop target.';
      actionUrl ??= 'https://docs.flutter.dev/get-started/install';
    } else if (item.id == 'flutter' || item.id == 'flutter_sdk') {
      solutionGuidance =
          'Install the official Flutter SDK and configure system PATH environment variables.';
      actionUrl ??= 'https://docs.flutter.dev/get-started/install';
      if (Platform.isWindows) {
        actionCommand ??= 'winget install Google.Flutter';
      }
    }

    if (actionUrl == null) {
      final urlMatch = RegExp(r'https?://[^\s\)\],]+').firstMatch(item.details);
      if (urlMatch != null) {
        actionUrl = urlMatch.group(0);
      }
    }

    if (actionCommand == null) {
      final tickMatch = RegExp(r'`(flutter\s+[^`]+)`').firstMatch(item.details);
      if (tickMatch != null) {
        actionCommand = tickMatch.group(1);
      }
    }

    return item.copyWith(
      solutionGuidance: solutionGuidance,
      actionCommand: actionCommand,
      actionUrl: actionUrl,
    );
  }
