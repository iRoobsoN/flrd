import 'dart:io';
import 'package:flutter/foundation.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

/// Represents the health status of a Flutter Doctor environment component.
enum DoctorItemStatus {
  healthy,
  warning,
  missing,
}

/// Represents an individual item / section parsed from `flutter doctor -v`.
class DoctorItem {
  final String id;
  final String title;
  final DoctorItemStatus status;
  final String details;
  final String? solutionGuidance;
  final String? actionCommand;
  final String? actionUrl;

  const DoctorItem({
    required this.id,
    required this.title,
    required this.status,
    required this.details,
    this.solutionGuidance,
    this.actionCommand,
    this.actionUrl,
  });

  bool get isHealthy => status == DoctorItemStatus.healthy;
  bool get isWarning => status == DoctorItemStatus.warning;
  bool get isMissing => status == DoctorItemStatus.missing;

  bool get hasAction =>
      (actionCommand != null && actionCommand!.trim().isNotEmpty) ||
      (actionUrl != null && actionUrl!.trim().isNotEmpty);

  DoctorItem copyWith({
    String? id,
    String? title,
    DoctorItemStatus? status,
    String? details,
    String? solutionGuidance,
    String? actionCommand,
    String? actionUrl,
  }) {
    return DoctorItem(
      id: id ?? this.id,
      title: title ?? this.title,
      status: status ?? this.status,
      details: details ?? this.details,
      solutionGuidance: solutionGuidance ?? this.solutionGuidance,
      actionCommand: actionCommand ?? this.actionCommand,
      actionUrl: actionUrl ?? this.actionUrl,
    );
  }

  @override
  String toString() =>
      'DoctorItem(id: $id, title: $title, status: $status, hasAction: $hasAction)';
}

/// Full diagnostic report generated by `FlutterDoctorService`.
class DoctorReport {
  final bool isScanning;
  final int healthyCount;
  final int totalCount;
  final List<DoctorItem> items;
  final String? rawOutput;
  final String? error;

  const DoctorReport({
    this.isScanning = false,
    this.healthyCount = 0,
    this.totalCount = 0,
    this.items = const [],
    this.rawOutput,
    this.error,
  });

  factory DoctorReport.initial() => const DoctorReport(
        isScanning: false,
        healthyCount: 0,
        totalCount: 0,
        items: [],
      );

  factory DoctorReport.scanning() => const DoctorReport(
        isScanning: true,
        healthyCount: 0,
        totalCount: 0,
        items: [],
      );

  /// Pre-flight report when Flutter SDK is missing from the system PATH.
  factory DoctorReport.missingSdk({String? error}) {
    final isWindows = !kIsWeb && Platform.isWindows;
    final item = DoctorItem(
      id: 'flutter_sdk',
      title: 'Flutter SDK',
      status: DoctorItemStatus.missing,
      details: 'Flutter executable was not found in your system PATH.\n'
          'The Flutter SDK is required to build, test, and run your desktop and mobile applications.',
      solutionGuidance:
          'Download and extract the Flutter SDK into a directory without spaces '
          '(e.g. C:\\src\\flutter on Windows or ~/flutter on macOS/Linux), '
          'then append its "bin" directory to your system PATH environment variable.',
      actionCommand: isWindows ? 'winget install Google.Flutter' : null,
      actionUrl: 'https://docs.flutter.dev/get-started/install',
    );

    return DoctorReport(
      isScanning: false,
      healthyCount: 0,
      totalCount: 1,
      items: [item],
      rawOutput: 'Flutter executable not found in PATH.',
      error: error ?? 'Flutter SDK is not installed or not available in system PATH.',
    );
  }

  /// Report for Web Sandbox environments where native shell execution is unavailable.
  factory DoctorReport.webSandbox() {
    const items = [
      DoctorItem(
        id: 'flutter_web',
        title: 'Flutter Web Sandbox',
        status: DoctorItemStatus.healthy,
        details: 'Running within web preview sandbox environment.',
        solutionGuidance: 'Full native compilation tools require desktop execution.',
      ),
      DoctorItem(
        id: 'browser_engine',
        title: 'Browser Runtime & CanvasKit',
        status: DoctorItemStatus.healthy,
        details: 'Chromium / CanvasKit rendering engine active.',
      ),
    ];
    return const DoctorReport(
      isScanning: false,
      healthyCount: 2,
      totalCount: 2,
      items: items,
      rawOutput: '[√] Flutter Web Sandbox\n[√] Browser Runtime & CanvasKit',
    );
  }

  /// Percentage score (0-100) of healthy components.
  int get scorePercentage =>
      totalCount > 0 ? ((healthyCount / totalCount) * 100).round() : 0;

  /// Fractional health score (0.0 - 1.0).
  double get healthScore =>
      totalCount > 0 ? (healthyCount / totalCount) : 0.0;

  /// True if any component is missing or has a warning.
  bool get hasIssues =>
      items.any((item) => item.status != DoctorItemStatus.healthy);

  /// True if all parsed items are completely healthy.
  bool get isAllHealthy => totalCount > 0 && healthyCount == totalCount;

  /// Number of items with warning status.
  int get warningCount =>
      items.where((item) => item.status == DoctorItemStatus.warning).length;

  /// Number of items with missing/error status.
  int get missingCount =>
      items.where((item) => item.status == DoctorItemStatus.missing).length;

  DoctorReport copyWith({
    bool? isScanning,
    int? healthyCount,
    int? totalCount,
    List<DoctorItem>? items,
    String? rawOutput,
    String? error,
  }) {
    return DoctorReport(
      isScanning: isScanning ?? this.isScanning,
      healthyCount: healthyCount ?? this.healthyCount,
      totalCount: totalCount ?? this.totalCount,
      items: items ?? this.items,
      rawOutput: rawOutput ?? this.rawOutput,
      error: error ?? this.error,
    );
  }
}

/// Runner function signature allowing dependency injection and mocking in tests.
typedef DoctorProcessRunner = Future<ProcessResult> Function(
  String executable,
  List<String> arguments, {
  bool runInShell,
});

/// Service and Riverpod StateNotifier for executing `flutter doctor -v`,
/// parsing diagnostic results, and enriching issues with actionable fixes.
class FlutterDoctorService extends StateNotifier<DoctorReport> {
  final DoctorProcessRunner _runner;

  FlutterDoctorService({
    bool autoScan = true,
    DoctorProcessRunner? processRunner,
  })  : _runner = processRunner ?? _defaultProcessRunner,
        super(DoctorReport.initial()) {
    if (autoScan) {
      runDoctor();
    }
  }

  static Future<ProcessResult> _defaultProcessRunner(
    String executable,
    List<String> arguments, {
    bool runInShell = true,
  }) {
    return Process.run(executable, arguments, runInShell: runInShell);
  }

  /// Executes `flutter doctor -v`, parses the output, enriches issues,
  /// and updates the provider state with the resulting [DoctorReport].
  Future<DoctorReport> runDoctor() async {
    if (kIsWeb) {
      final report = DoctorReport.webSandbox();
      if (mounted) state = report;
      return report;
    }

    if (mounted) {
      state = state.copyWith(isScanning: true, error: null);
    }

    try {
      final isWindows = !kIsWeb && Platform.isWindows;

      // 1. Pre-flight check: Verify if flutter executable exists in PATH
      final locatorCmd = isWindows ? 'where.exe' : 'which';
      try {
        final locatorRes = await _runner(
          locatorCmd,
          ['flutter'],
          runInShell: isWindows,
        );
        if (locatorRes.exitCode != 0) {
          final report = DoctorReport.missingSdk(
            error: 'Flutter executable not found in system PATH.',
          );
          if (mounted) state = report;
          return report;
        }
      } catch (_) {
        // If locator command isn't available, proceed to run flutter directly
      }

      // 2. Execute `flutter doctor -v`
      final doctorRes = await _runner(
        'flutter',
        ['doctor', '-v'],
        runInShell: true,
      );

      final stdoutText = doctorRes.stdout?.toString() ?? '';
      final stderrText = doctorRes.stderr?.toString() ?? '';
      final combinedOutput = '$stdoutText\n$stderrText'.trim();

      if (combinedOutput.isEmpty && doctorRes.exitCode != 0) {
        final report = DoctorReport.missingSdk(
          error: 'Flutter doctor exited with code ${doctorRes.exitCode}.',
        );
        if (mounted) state = report;
        return report;
      }

      // 3. Parse and enrich doctor items
      final parsedReport = parseDoctorOutput(combinedOutput);

      // If output could not be parsed into any items, handle gracefully
      if (parsedReport.items.isEmpty) {
        final fallback = DoctorReport(
          isScanning: false,
          healthyCount: 0,
          totalCount: 0,
          items: const [],
          rawOutput: combinedOutput,
          error: combinedOutput.isNotEmpty
              ? 'Could not parse flutter doctor output.'
              : 'Doctor output was empty.',
        );
        if (mounted) state = fallback;
        return fallback;
      }

      if (mounted) state = parsedReport;
      return parsedReport;
    } catch (e) {
      final report = DoctorReport.missingSdk(error: e.toString());
      if (mounted) state = report;
      return report;
    }
  }

  /// Parses raw `flutter doctor -v` string output into a structured [DoctorReport].
  static DoctorReport parseDoctorOutput(String rawOutput) {
    if (rawOutput.trim().isEmpty) {
      return DoctorReport.initial();
    }

    final lines = rawOutput.split(RegExp(r'\r?\n'));
    final List<DoctorItem> items = [];

    // Header regex: [√], [✓], [!], [X], [x], [✗], [+], [-]
    final headerRegex = RegExp(r'^[ \t]*\[([√✓xX✗!+?•\-])\]\s*(.+)$');

    String? currentSymbol;
    String? currentTitle;
    final List<String> currentDetails = [];

    void finalizeCurrentItem() {
      if (currentSymbol == null || currentTitle == null) return;

      final status = _mapSymbolToStatus(currentSymbol!);
      final rawTitle = currentTitle!.trim();
      // Remove trailing timing metrics e.g. " [192ms]" or " [1.2s]"
      final cleanedTitle = rawTitle
          .replaceAll(RegExp(r'\s*\[\d+(?:\.\d+)?m?s\]\s*$'), '')
          .trim();

      final details = currentDetails.join('\n').trim();
      final id = _generateId(cleanedTitle, items.length);

      final rawItem = DoctorItem(
        id: id,
        title: cleanedTitle,
        status: status,
        details: details,
      );

      final enrichedItem = enrichDoctorItem(rawItem);
      items.add(enrichedItem);

      currentSymbol = null;
      currentTitle = null;
      currentDetails.clear();
    }

    for (final line in lines) {
      final match = headerRegex.firstMatch(line);
      if (match != null) {
        // We found a new section header
        finalizeCurrentItem();
        currentSymbol = match.group(1);
        currentTitle = match.group(2);
      } else {
        final trimmed = line.trim();
        // Ignore doctor summary/footer lines
        final isFooter = trimmed.startsWith('! Doctor found issues') ||
            trimmed.startsWith('• No issues found!') ||
            trimmed.startsWith('! No issues found') ||
            trimmed.startsWith('• Doctor found');

        if (isFooter) {
          finalizeCurrentItem();
        } else if (currentSymbol != null) {
          currentDetails.add(line);
        }
      }
    }

    // Finalize the last remaining item if any
    finalizeCurrentItem();

    final healthyCount =
        items.where((i) => i.status == DoctorItemStatus.healthy).length;

    return DoctorReport(
      isScanning: false,
      healthyCount: healthyCount,
      totalCount: items.length,
      items: items,
      rawOutput: rawOutput,
    );
  }

  /// Maps doctor status symbols to [DoctorItemStatus].
  static DoctorItemStatus _mapSymbolToStatus(String symbol) {
    switch (symbol) {
      case '√':
      case '✓':
      case '+':
        return DoctorItemStatus.healthy;
      case '!':
        return DoctorItemStatus.warning;
      case 'X':
      case 'x':
      case '✗':
        return DoctorItemStatus.missing;
      default:
        return DoctorItemStatus.warning;
    }
  }

  /// Generates a standardized, semantic ID for a doctor item based on its title.
  static String _generateId(String title, int index) {
    final lower = title.toLowerCase();
    if (lower.startsWith('flutter')) return 'flutter';
    if (lower.contains('android studio')) return 'android_studio';
    if (lower.contains('android toolchain') ||
        (lower.contains('android') && !lower.contains('studio'))) {
      return 'android_toolchain';
    }
    if (lower.contains('windows version')) return 'windows_version';
    if (lower.contains('visual studio')) return 'visual_studio';
    if (lower.contains('xcode')) return 'xcode';
    if (lower.contains('chrome')) return 'chrome';
    if (lower.contains('linux toolchain') || lower.contains('linux')) {
      return 'linux_toolchain';
    }
    if (lower.contains('connected device')) return 'connected_device';
    if (lower.contains('network resources') || lower.contains('network')) {
      return 'network_resources';
    }
    if (lower.contains('cocoapods')) return 'cocoapods';

    final slug = lower
        .split(RegExp(r'[^a-z0-9]+'))
        .where((s) => s.isNotEmpty)
        .take(3)
        .join('_');

    return slug.isNotEmpty ? slug : 'doctor_item_$index';
  }

  /// Enriches a [DoctorItem] with actionable quick-fix URLs, terminal commands,
  /// and human-friendly step-by-step guidance.
  static DoctorItem enrichDoctorItem(DoctorItem item) {
    // Healthy items do not strictly require remediation guidance
    if (item.status == DoctorItemStatus.healthy) {
      return item;
    }

    String? solutionGuidance = item.solutionGuidance;
    String? actionCommand = item.actionCommand;
    String? actionUrl = item.actionUrl;

    final titleLower = item.title.toLowerCase();
    final detailsLower = item.details.toLowerCase();

    // 1. Android Licenses issue
    if (detailsLower.contains('android-licenses') ||
        detailsLower.contains('licenses not accepted') ||
        detailsLower.contains('licenses of some android sdk') ||
        detailsLower.contains('license status')) {
      solutionGuidance =
          'Accept the Android SDK platform licenses by executing the license command in your terminal and accepting all terms.';
      actionCommand = 'flutter doctor --android-licenses';
      actionUrl ??= 'https://flutter.dev/to/windows-android-setup';
    }
    // 2. Android SDK / Android Studio missing
    else if (item.id == 'android_toolchain' ||
        item.id == 'android_studio' ||
        titleLower.contains('android')) {
      if (detailsLower.contains('unable to locate android sdk') ||
          detailsLower.contains('android studio not installed') ||
          detailsLower.contains('android sdk not found') ||
          detailsLower.contains('install android studio')) {
        solutionGuidance =
            'Install Android Studio to configure the official Android SDK, Platform-Tools, and Virtual Device Emulators.';
        actionUrl ??= 'https://developer.android.com/studio';
        if (detailsLower.contains('flutter config --android-sdk')) {
          actionCommand = 'flutter config --android-sdk';
        }
      } else if (detailsLower.contains('cmdline-tools component is missing') ||
          detailsLower.contains('cmdline-tools')) {
        solutionGuidance =
            'Open Android Studio > SDK Manager > SDK Tools tab, check "Android SDK Command-line Tools (latest)", and click Apply.';
        actionUrl ??= 'https://developer.android.com/studio';
      }
    }
    // 3. Visual Studio / Windows C++ Build Tools
    else if (item.id == 'visual_studio' || titleLower.contains('visual studio')) {
      solutionGuidance =
          'Install Visual Studio 2022 with the "Desktop development with C++" workload '
          '(including MSVC v143 and Windows 10/11 SDK) to build native Windows desktop applications.';
      actionUrl ??= 'https://visualstudio.microsoft.com/downloads/';
      if (!kIsWeb && Platform.isWindows) {
        actionCommand ??= 'winget install Microsoft.VisualStudio.2022.BuildTools';
      }
    }
    // 4. Google Chrome (Web development)
    else if (item.id == 'chrome' || titleLower.contains('chrome')) {
      solutionGuidance =
          'Install Google Chrome to develop, debug, and preview Flutter Web applications.';
      actionUrl ??= 'https://www.google.com/chrome/';
    }
    // 5. CocoaPods (often reported under the Xcode section in doctor: "CocoaPods not installed")
    else if (item.id == 'cocoapods' ||
        titleLower.contains('cocoapods') ||
        detailsLower.contains('cocoapods not installed') ||
        detailsLower.contains('cocoapods')) {
      solutionGuidance =
          'Install CocoaPods to resolve iOS and macOS native pod dependencies.';
      actionCommand = 'sudo gem install cocoapods';
      actionUrl = 'https://guides.cocoapods.org/using/getting-started.html';
    }
    // 6. Xcode (iOS / macOS development)
    else if (item.id == 'xcode' || titleLower.contains('xcode')) {
      solutionGuidance =
          'Install Xcode from the Mac App Store and run initial command-line setup to support iOS and macOS development.';
      actionUrl ??= 'https://developer.apple.com/xcode/';
      actionCommand ??=
          'sudo xcode-select --switch /Applications/Xcode.app/Contents/Developer && sudo xcodebuild -runFirstLaunch';
    }
    // 7. Linux desktop toolchain
    else if (item.id == 'linux_toolchain' || titleLower.contains('linux')) {
      solutionGuidance =
          'Install required Linux build packages (clang, cmake, ninja-build, pkg-config, libgtk-3-dev).';
      actionCommand ??=
          'sudo apt-get install clang cmake ninja-build pkg-config libgtk-3-dev';
      actionUrl ??= 'https://docs.flutter.dev/get-started/install/linux/desktop';
    }
    // 8. Connected Devices
    else if (item.id == 'connected_device' ||
        titleLower.contains('connected device')) {
      solutionGuidance =
          'Connect a physical device via USB with USB debugging enabled, or launch an emulator / desktop target.';
      actionUrl ??= 'https://docs.flutter.dev/get-started/install';
    }
    // 9. Missing Flutter SDK itself
    else if (item.id == 'flutter' || item.id == 'flutter_sdk') {
      solutionGuidance =
          'Install the official Flutter SDK and configure system PATH environment variables.';
      actionUrl ??= 'https://docs.flutter.dev/get-started/install';
      if (!kIsWeb && Platform.isWindows) {
        actionCommand ??= 'winget install Google.Flutter';
      }
    }

    // Dynamic extraction: extract URL from details if not yet assigned
    if (actionUrl == null) {
      final urlMatch = RegExp(r'https?://[^\s\)\],]+').firstMatch(item.details);
      if (urlMatch != null) {
        actionUrl = urlMatch.group(0);
      }
    }

    // Dynamic extraction: extract command from backticks or flutter commands if not yet assigned
    if (actionCommand == null) {
      final tickMatch = RegExp(r'`(flutter\s+[^`]+)`').firstMatch(item.details);
      if (tickMatch != null) {
        actionCommand = tickMatch.group(1);
      }
    }

    return item.copyWith(
      solutionGuidance: solutionGuidance,
      actionCommand: actionCommand,
      actionUrl: actionUrl,
    );
  }
}

/// Global Riverpod StateNotifierProvider for [FlutterDoctorService].
final flutterDoctorProvider =
    StateNotifierProvider<FlutterDoctorService, DoctorReport>((ref) {
  return FlutterDoctorService();
});
